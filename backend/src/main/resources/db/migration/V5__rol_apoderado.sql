-- =====================================================================
--  Migración V5: rol APODERADO (padre, madre o tutor) y su vínculo con el alumno
--  Un apoderado solo ve el avance de los alumnos que el administrador le vinculó.
--  El vínculo lo crea únicamente el administrador, tras verificar la relación con la familia.
-- =====================================================================
INSERT INTO roles (nombre, descripcion)
VALUES ('APODERADO', 'Padre, madre o tutor: consulta el avance de los alumnos que tiene vinculados');

CREATE TABLE vinculos_apoderado (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    apoderado_id  BIGINT      NOT NULL,
    alumno_id     BIGINT      NOT NULL,
    parentesco    VARCHAR(15) NOT NULL DEFAULT 'APODERADO',
    creado_por    BIGINT,
    creado_en     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_vinculos_apoderado PRIMARY KEY (id),
    CONSTRAINT uq_vinculo_apoderado_alumno UNIQUE (apoderado_id, alumno_id),
    CONSTRAINT fk_vinculo_apoderado FOREIGN KEY (apoderado_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_vinculo_alumno FOREIGN KEY (alumno_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_vinculo_creador FOREIGN KEY (creado_por) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT ck_vinculo_distintos CHECK (apoderado_id <> alumno_id),
    CONSTRAINT ck_vinculo_parentesco CHECK (parentesco IN ('PADRE', 'MADRE', 'TUTOR', 'APODERADO'))
);
CREATE INDEX idx_vinculos_apoderado ON vinculos_apoderado (apoderado_id);
CREATE INDEX idx_vinculos_alumno ON vinculos_apoderado (alumno_id);
