-- =====================================================================
--  Migración V6 (RFC-2026-001): mesa de ayuda para las solicitudes de servicio (ITIL 4).
--  Alumnos y apoderados registran solicitudes de información, acceso o soporte;
--  el administrador las atiende dentro del tiempo comprometido (SLA) de cada tipo.
--  Cambio compatible hacia atrás: solo agrega una tabla nueva, la versión 1.5 sigue funcionando
--  sobre este esquema, lo que permite revertir la aplicación sin tocar la base de datos.
-- =====================================================================
CREATE TABLE solicitudes_servicio (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    solicitante_id  BIGINT        NOT NULL,
    tipo            VARCHAR(25)   NOT NULL,
    prioridad       VARCHAR(10)   NOT NULL,
    estado          VARCHAR(15)   NOT NULL DEFAULT 'ABIERTA',
    asunto          VARCHAR(120)  NOT NULL,
    descripcion     VARCHAR(1000) NOT NULL,
    respuesta       VARCHAR(1000),
    atendido_por    BIGINT,
    creado_en       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vence_en        TIMESTAMP     NOT NULL,
    resuelto_en     TIMESTAMP,
    CONSTRAINT pk_solicitudes_servicio PRIMARY KEY (id),
    CONSTRAINT fk_solserv_solicitante FOREIGN KEY (solicitante_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_solserv_atendido FOREIGN KEY (atendido_por) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT ck_solserv_tipo CHECK (tipo IN ('INFORMACION', 'ACCESO_CUENTA', 'RESTABLECER_PASSWORD',
                                               'CAMBIO_HORARIO', 'VINCULO_APODERADO', 'SOPORTE_TECNICO')),
    CONSTRAINT ck_solserv_prioridad CHECK (prioridad IN ('ALTA', 'MEDIA', 'BAJA')),
    CONSTRAINT ck_solserv_estado CHECK (estado IN ('ABIERTA', 'EN_PROCESO', 'RESUELTA', 'CERRADA', 'RECHAZADA')),
    CONSTRAINT ck_solserv_vence CHECK (vence_en > creado_en)
);
CREATE INDEX idx_solserv_solicitante ON solicitudes_servicio (solicitante_id);
CREATE INDEX idx_solserv_estado ON solicitudes_servicio (estado);
